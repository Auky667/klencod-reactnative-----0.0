import type { Topic } from "@/types";

function mk(
  prefix: string,
  n: number,
  title: string,
  summary: string,
  content: string[],
  evidences: [string, string][],
  benefits: string[],
  references: string[],
): Topic {
  return {
    id: `${prefix}-${n}`,
    title,
    summary,
    content,
    evidences: evidences.map(([text, source]) => ({ text, source })),
    benefits,
    references,
  };
}

