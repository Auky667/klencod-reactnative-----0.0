import type { Topic } from "@/types";

/**
 * بناء موضوع بمُعرّف ثابت «seerah-<رقم>» يعتمد عليه في المفضلة والبحث.
 * الشكل السابع: [نص الدليل، مصدره] ثم الفوائد ثم المراجع.
 * الشكل السادس: الفوائد ثم المراجع (ويُستكمل الدليل من خريطة الأدلة).
 */
type EvidenceTuple = [string, string];

function mk(
  n: number,
  title: string,
  summary: string,
  content: string[],
  first: EvidenceTuple[] | string[],
  benefitsArg?: string[],
  referencesArg?: string[],
): Topic {
  const hasEvidenceBlock = Array.isArray(first[0]);
  const evidences: EvidenceTuple[] = hasEvidenceBlock
    ? (first as EvidenceTuple[])
    : (EVENT_EVIDENCES[n] ?? []);
  const benefits = hasEvidenceBlock ? (benefitsArg as string[]) : (first as string[]);
  const references = hasEvidenceBlock ? (referencesArg as string[]) : (benefitsArg as string[]);

  return {
    id: `seerah-${n}`,
    title,
    summary,
    content,
    evidences: evidences.map(([text, source]) => ({ text, source })),
    benefits,
    references,
  };
}

