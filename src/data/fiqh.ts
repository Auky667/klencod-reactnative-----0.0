import type { FiqhSection, Topic } from "@/types";

/** بناء موضوع فقهي بمُعرّف ثابت «fiqh-<الباب>-<الرقم>» */
function t(
  id: string,
  title: string,
  summary: string,
  content: string[],
  evidences: [string, string][],
  benefits: string[],
  references: string[],
): Topic {
  return {
    id: `fiqh-${id}`,
    title,
    summary,
    content,
    evidences: evidences.map(([text, source]) => ({ text, source })),
    benefits,
    references,
  };
}

const section = (
  id: string,
  title: string,
  description: string,
  topics: Topic[],
): FiqhSection => ({ id, title, description, topics });

